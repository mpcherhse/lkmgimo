def P(text, st="p"):
    return Paragraph(text, S[st])


def bullets(items):
    return [Paragraph(t, S["li"], bulletText="•") for t in items]


def table(rows, widths, header=True):
    data = [[Paragraph(str(c), S["cellb" if (header and i == 0) else "cell"]) for c in r] for i, r in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.5, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5), ("TOPPADDING", (0, 0), (-1, -1), 3),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), TINT))
    t.setStyle(TableStyle(style))
    return t


def shot(name, caption, width=W, max_h=150 * mm):
    path = SCREENS / f"{name}.jpg"
    if not path.exists():
        return [P(f"[нет скриншота {name}]", "small")]
    iw, ih = ImageReader(str(path)).getSize()
    w = width
    h = w * ih / iw
    if h > max_h:
        h = max_h
        w = h * iw / ih
    img = Image(str(path), width=w, height=h)
    img.hAlign = "LEFT"
    box = Table([[img]], colWidths=[w + 2])
    box.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, LINE), ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                             ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    box.hAlign = "LEFT"
    return [KeepTogether([box, P(caption, "cap")])]


def pair(a, b, cap):
    """два скриншота телефона рядом"""
    cells = []
    for name in (a, b):
        path = SCREENS / f"{name}.jpg"
        iw, ih = ImageReader(str(path)).getSize()
        h = 120 * mm
        w = h * iw / ih
        cells.append(Image(str(path), width=w, height=h))
    t = Table([cells], colWidths=[W / 2, W / 2])
    t.setStyle(TableStyle([("ALIGN", (0, 0), (-1, -1), "CENTER")]))
    return [KeepTogether([t, P(cap, "cap")])]


def on_page(c, doc):
    c.saveState()
    c.setFont("PT", 7.5)
    c.setFillColor(GREY)
    c.drawString(18 * mm, 10 * mm, "Цифровой деканат — концепт для конкурса «Цифровой деканат будущего». Не официальный сервис МГИМО, данные вымышлены.")
    c.drawRightString(A4[0] - 18 * mm, 10 * mm, str(doc.page))
    c.restoreState()


